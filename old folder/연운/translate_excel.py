NS = 'http://schemas.openxmlformats.org/spreadsheetml/2006/main'

def process_shared_strings(xml_data):
    """sharedStrings.xml의 텍스트 번역"""
    # 네임스페이스 등록 (직렬화시 ns0: 방지)
    ET.register_namespace('', NS)
    # 기타 네임스페이스도 보존
    for ns_uri in ['http://schemas.openxmlformats.org/markup-compatibility/2006',
                    'http://schemas.microsoft.com/office/spreadsheetml/2009/9/main']:
        prefix = 'mc' if 'compatibility' in ns_uri else 'x14ac'
        try:
            ET.register_namespace(prefix, ns_uri)
        except:
            pass
    
    root = ET.fromstring(xml_data)
    ns = {'s': NS}
    
    translated_count = 0
    for idx, si in enumerate(root.findall('s:si', ns)):
        # 모든 <t> 텍스트 수집
        texts = []
        for t_elem in si.iter(f'{{{NS}}}t'):
            if t_elem.text:
                texts.append(t_elem.text)
        original = ''.join(texts)
        translated = translate_text(original, idx)
        
        if translated != original:
            translated_count += 1
            # 자식 요소 모두 제거 후 단일 <t>로 대체
            for child in list(si):
                si.remove(child)
            t_new = ET.SubElement(si, f'{{{NS}}}t')
            t_new.text = translated
            if translated and (translated[0] == ' ' or translated[-1] == ' '):
                t_new.set('{http://www.w3.org/XML/1998/namespace}space', 'preserve')
    
    print(f"  번역된 문자열: {translated_count}/{idx+1}개")
    return ET.tostring(root, encoding='UTF-8', xml_declaration=True)

def process_workbook(xml_data):
    """workbook.xml의 시트명 변경"""
    xml_str = xml_data.decode('utf-8')
    for old_name, new_name in SHEET_NAME_MAP.items():
        # XML 속성 내에서 & → &amp;
        old_esc = old_name.replace('&', '&amp;')
        new_esc = new_name.replace('&', '&amp;')
        xml_str = xml_str.replace(f'name="{old_esc}"', f'name="{new_esc}"')
    return xml_str.encode('utf-8')

def process_worksheet(xml_data):
    """워크시트의 수식 내 시트명 참조 업데이트"""
    xml_str = xml_data.decode('utf-8')
    for old_name, new_name in SHEET_NAME_MAP.items():
        # 따옴표로 감싼 참조: 'Sheet Name'!
        xml_str = xml_str.replace(f"'{old_name}'!", f"'{new_name}'!")
        # 따옴표 없는 참조: SheetName!
        xml_str = xml_str.replace(f"{old_name}!", f"{new_name}!")
        # XML 이스케이프된 &amp; 처리
        old_esc = old_name.replace('&', '&amp;')
        if old_esc != old_name:
            new_esc = new_name.replace('&', '&amp;')
            xml_str = xml_str.replace(f"'{old_esc}'!", f"'{new_esc}'!")
            xml_str = xml_str.replace(f"{old_esc}!", f"{new_esc}!")
    return xml_str.encode('utf-8')

