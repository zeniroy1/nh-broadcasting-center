TERM_DICT = sorted(TERM_DICT_RAW, key=lambda x: len(x[0]), reverse=True)

# ============================================================
# 번역 함수
# ============================================================
def translate_text(text, idx=None):
    """공유 문자열 번역"""
    if not text or not text.strip():
        return text
    # 숫자만 있으면 스킵
    if re.match(r'^[\d\.\-\+\%\s\,]+$', text):
        return text
    # URL 스킵
    if text.startswith('http'):
        return text
    # 후원자 닉네임 (*로 시작) 스킵
    if text.startswith('*') or re.match(r'^[A-Z]\*[a-z]$', text):
        return text
    
    result = text
    for src, tgt in TERM_DICT:
        if src in result:
            result = result.replace(src, tgt)
    return result

