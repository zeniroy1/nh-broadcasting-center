def main():
    print(f"원본: {SOURCE}")
    print(f"출력: {OUTPUT}")
    
    if not os.path.exists(SOURCE):
        print("오류: 원본 파일을 찾을 수 없습니다!")
        return
    
    print("\n번역 시작...")
    with zipfile.ZipFile(SOURCE, 'r') as zin:
        with zipfile.ZipFile(OUTPUT, 'w', zipfile.ZIP_DEFLATED) as zout:
            for item in zin.infolist():
                data = zin.read(item.filename)
                
                if item.filename == 'xl/sharedStrings.xml':
                    print(f"\n[1/3] 공유 문자열 번역 중...")
                    data = process_shared_strings(data)
                elif item.filename == 'xl/workbook.xml':
                    print(f"[2/3] 시트명 번역 중...")
                    data = process_workbook(data)
                elif item.filename.startswith('xl/worksheets/sheet'):
                    sheet_num = item.filename.split('sheet')[1].split('.')[0]
                    print(f"[3/3] 시트{sheet_num} 수식 업데이트 중...")
                    data = process_worksheet(data)
                
                zout.writestr(item, data)
    
    file_size = os.path.getsize(OUTPUT)
    print(f"\n✅ 번역 완료!")
    print(f"   파일: {OUTPUT}")
    print(f"   크기: {file_size:,} bytes")

if __name__ == '__main__':
    main()
